#!/usr/bin/env python3
"""
Hugh Player // USB Agent Vault Bridge 🏛️⚡
Hugh Development — Co-founders: Hugh & Atom

This CLI bridge connects your PC to your Android device via USB/ADB,
allowing AI agents (Atom, Codex, ChatGPT, Hermes Agent) to:
1. Pull the JSON music manifest from the phone.
2. Inspect and organize music files on the phone's storage.
3. Automatically trigger Android MediaScanner so Hugh Player reflects changes instantly.
"""

import sys
import os
import json
import subprocess
import argparse

MANIFEST_REMOTE_PATH = "/sdcard/Download/hugh_vault_ai_manifest.json"
MANIFEST_LOCAL_PATH = "hugh_vault_ai_manifest.json"

def run_adb(cmd_list):
    """Executes an adb command safely and returns stdout."""
    try:
        full_cmd = ["adb"] + cmd_list
        res = subprocess.run(full_cmd, capture_output=True, text=True, check=True)
        return res.stdout.strip()
    except FileNotFoundError:
        print("❌ [ERRO] 'adb' não encontrado no PATH.")
        print("💡 Instale o Android SDK Platform-Tools ou certifique-se de que o ADB está acessível.")
        sys.exit(1)
    except subprocess.CalledProcessError as e:
        print(f"❌ [ERRO ADB] {e.stderr.strip()}")
        return None

def check_device():
    """Verifies that an Android device is connected via USB."""
    out = run_adb(["devices"])
    lines = [l for l in out.splitlines() if l and not l.startswith("List of devices")]
    connected = [l.split("\t")[0] for l in lines if "\tdevice" in l]
    if not connected:
        print("❌ Nenhum celular Android autorizado detectado via USB.")
        print("👉 Dica: Ative a 'Depuração USB' nas Opções de Desenvolvedor do celular.")
        sys.exit(1)
    model = run_adb(["shell", "getprop", "ro.product.model"])
    print(f"📱 Dispositivo conectado com sucesso: {model} (ID: {connected[0]})")
    return connected[0]

def pull_manifest():
    """Pulls the JSON manifest generated by Hugh Player Settings."""
    check_device()
    print(f"📥 Baixando manifesto de {MANIFEST_REMOTE_PATH}...")
    res = run_adb(["pull", MANIFEST_REMOTE_PATH, MANIFEST_LOCAL_PATH])
    if res and os.path.exists(MANIFEST_LOCAL_PATH):
        with open(MANIFEST_LOCAL_PATH, "r", encoding="utf-8") as f:
            data = json.load(f)
        total = data.get("total_songs", len(data.get("library", [])))
        print(f"✅ Manifesto baixado com sucesso! Total de músicas catalogadas: {total}")
        return data
    else:
        print("⚠️ Manifesto não encontrado no celular.")
        print("👉 Abra o Hugh Player -> Configurações -> 'GERAR MANIFESTO JSON NA PASTA DOWNLOADS' e tente novamente.")
        return None

def trigger_rescan(path="/sdcard/Music"):
    """Notifies Android MediaScanner to index newly moved or tagged music files."""
    check_device()
    print(f"🔄 Solicitando rescan do MediaStore para: {path}...")
    run_adb(["shell", "am", "broadcast", "-a", "android.intent.action.MEDIA_SCANNER_SCAN_FILE", "-d", f"file://{path}"])
    print("✅ Rescan concluído! Abra o Hugh Player e toque em Atualizar para sincronizar.")

def generate_ai_prompt():
    """Generates a ready-to-use prompt for LLMs (ChatGPT, Hermes, Claude) with the library context."""
    if not os.path.exists(MANIFEST_LOCAL_PATH):
        data = pull_manifest()
        if not data:
            return
    else:
        with open(MANIFEST_LOCAL_PATH, "r", encoding="utf-8") as f:
            data = json.load(f)

    songs = data.get("library", [])
    prompt = f"""VOCÊ É O AGENTE DE IA DA HUGH DEVELOPMENT (PARCEIRO DO HUGH E ATOM).
Aqui está a lista completa de faixas locais do usuário extraída do Hugh Player:

TOTAL DE MÚSICAS: {len(songs)}

LISTA DE ARQUIVOS:
"""
    for idx, s in enumerate(songs[:150], 1):
        prompt += f"{idx}. [{s.get('artist')}] {s.get('title')} (Álbum: {s.get('album')}) -> Path: {s.get('path')}\n"

    prompt += """
TAREFA:
1. Agrupe essas músicas por estilos/vibes (ex: Treino, Foco, Neoclassical, Phonk, Noturno).
2. Sugira uma estrutura de pastas organizada no formato: /Music/<Estilo>/<Artista> - <Titulo>.mp3.
3. Gere um plano com comandos adb shell mv para executar a reorganização.
"""
    prompt_file = "ai_prompt_vault.txt"
    with open(prompt_file, "w", encoding="utf-8") as f:
        f.write(prompt)
    print(f"📋 Prompt gerado em '{prompt_file}'! Copie o conteúdo ou envie para o seu agente.")

def main():
    parser = argparse.ArgumentParser(description="Hugh Player // USB Agent Vault Bridge")
    subparsers = parser.add_subparsers(dest="command")

    subparsers.add_parser("status", help="Verifica a conexão USB com o celular")
    subparsers.add_parser("pull", help="Baixa o manifesto da biblioteca gerado pelo app")
    subparsers.add_parser("prompt", help="Gera um prompt de IA com todas as músicas para ChatGPT/Hermes")
    
    rescan_p = subparsers.add_parser("rescan", help="Força o celular a atualizar a biblioteca de áudio")
    rescan_p.add_argument("--path", default="/sdcard/Music", help="Caminho para reindexar")

    args = parser.parse_args()

    if args.command == "status":
        check_device()
    elif args.command == "pull":
        pull_manifest()
    elif args.command == "prompt":
        generate_ai_prompt()
    elif args.command == "rescan":
        trigger_rescan(args.path)
    else:
        parser.print_help()

if __name__ == "__main__":
    main()
